  <h4 class="m-2 text-lg font-bold">
    Volcano Heart Cauldron
  </h4>
  <div class="mx-4 text-md">
    <p>
      A machine block that slowly converts <strong>Deepslate</strong> into a
      <strong>Lava Source</strong> in the space directly below it.
    </p>
    <ul class="list-disc mx-6 my-2">
      <li>Right-click the block to open its GUI.</li>
      <li>Place a <strong>full stack of Deepslate</strong> in the input slot.</li>
      <li>The block below the machine must be empty (air) or a fluid that lava can replace.</li>
      <li>While both conditions are met, the progress bar fills up over 5 seconds.</li>
      <li>When complete, one stack of Deepslate is consumed and a Lava Source appears below the machine.</li>
      <li>If conditions stop being met, progress slowly drains instead of resetting instantly.</li>
    </ul>
  </div>

  <h4 class="m-2 text-lg font-bold">
    Nature Heart Cauldron
  </h4>
  <div class="mx-4 text-md">
    <p>
      A machine block that slowly converts <strong>Any leaves</strong> into a
      <strong>Water Source</strong> in the space directly below it.
    </p>
    <ul class="list-disc mx-6 my-2">
      <li>Right-click the block to open its GUI.</li>
      <li>Place a <strong>full stack of any Leaves</strong> in the input slot.</li>
      <li>The block below the machine must be empty (air) or a fluid that water can replace.</li>
      <li>While both conditions are met, the progress bar fills up over 5 seconds.</li>
      <li>When complete, one stack of the Leaves placed is consumed and a Water Source appears below the machine.</li>
      <li>If conditions stop being met, progress slowly drains instead of resetting instantly.</li>
    </ul>
  </div>

